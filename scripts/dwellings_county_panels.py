def _row_baselines(words: list, lo: float, hi: float) -> list[float]:
    lines: list[list] = []
    for word in sorted(words, key=lambda item: ((item[1] + item[3]) / 2, item[0])):
        y = (word[1] + word[3]) / 2
        if word[0] >= 115 or word[2] >= 128 or not lo < y < hi:
            continue
        if not re.search(r"[A-Za-z]", word[4]):
            continue
        if lines and abs(y - lines[-1][0]) < 3:
            lines[-1][1].append(word[4])
        else:
            lines.append([y, [word[4]]])
    # These are the printed multi-line section headings, not geography rows.
    return [y for y, tokens in lines
            if not re.search(r"REMAINDER|RJ;lMAINDER|STATE-", " ".join(tokens))]


def _number(word: tuple) -> str | None:
    text = word[4]
    # A tall I is a vertical table rule, not an inmate/dwelling count of one.
    if text in ("I", "l") and word[3] - word[1] > 13:
        return None
    text = text.strip(".,;:\"'!|")
    if not re.fullmatch(r"[\d,IlOo]+", text):
        return None
    return text.translate(str.maketrans({"I": "1", "l": "1", "O": "0", "o": "0"}))


def _panel_values(words: list, baselines: list[float], centres: list[float],
                  lo: float, hi: float) -> list[dict[int, str]]:
    values: list[dict[int, str]] = [{} for _ in baselines]
    for word in words:
        x, y = (word[0] + word[2]) / 2, (word[1] + word[3]) / 2
        if not centres[0] - 16 < x < centres[-1] + 18 or not lo < y < hi:
            continue
        row = min(range(len(baselines)), key=lambda index: abs(baselines[index] - y))
        if abs(baselines[row] - y) > 4.1:
            continue
        column = min(range(len(centres)), key=lambda index: abs(centres[index] - x))
        value = _number(word)
        if value is not None:
            values[row][column] = value
    return values


def assemble_county_panels(
    source_rows: list[dict],
    schema: tuple[list[str], list[str], str],
    states: dict[int, list[tuple[float, str]]],
    area_types: dict[int, list[tuple[float, str]]],
) -> tuple[list[str], list[list[str]]]:
    """Return every printed Table 65 geography and all 35 printed data fields.

    Candidate rows and inferred context markers are accepted for the exporter's
    assembly interface, but cannot establish this table's row/column alignment.
    Physical PDF bands supply state/area context, including all three territories
    panels sharing pages 165-167. The legacy schema's missing category pairs are
    replaced with TABLE65_FIELDS rather than silently losing printed columns.
    """
    dimensions, _, _ = schema
    grouped: dict[tuple[str, str], dict[int, str]] = {}
    contexts: dict[tuple[str, str], dict[str, str]] = {}
    cursors: dict[tuple[str, int], int] = defaultdict(int)
    with pymupdf.open(PDF) as document:
        page_words: dict[int, list] = {}
        for page, lo, hi, state, area_type, offset, count in PANELS:
            if page not in page_words:
                page_words[page] = document[page - 1].get_text("words")
            words = page_words[page]
            baselines = _row_baselines(words, lo, hi)
            if len(baselines) != count:
                raise ValueError(f"Table 65 page {page}/{offset}: expected {count} printed rows, got {len(baselines)}")
            centres = (FINAL_CENTRES[page] if offset == 24 else
                       [MATERIAL_FIRST_CENTRE[page] + 31.4 * index for index in range(12)])
            if page == 155 and offset == 0:
                centres = [150 + 31.4 * index for index in range(12)]
            values = _panel_values(words, baselines, centres, lo, hi)
            start = cursors[state, offset]
            names = GEOGRAPHIES[state][start:start + count]
            if len(names) != count:
                raise ValueError(f"Table 65 {state}/{offset}: unmatched printed geography panel")
            cursors[state, offset] += count
            for name, row in zip(names, values):
                row.update(PRINTED_RECOVERIES.get((page, offset, state, name), {}))
                key = state, name
                target = grouped.setdefault(key, {})
                target.update({offset + column: value for column, value in row.items()})
                contexts[key] = {"state": state, "area_type": area_type, "area": name}
    headers = dimensions + TABLE65_FIELDS
    result = [[contexts[key].get(field, "") for field in dimensions] +
              [values.get(index, "") for index in range(len(TABLE65_FIELDS))]
              for key, values in grouped.items()]
    return headers, result
